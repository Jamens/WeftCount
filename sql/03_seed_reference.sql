-- ============================================================
-- WeftCount · 演示数据说明（不提供 INSERT 语句，请用 seed 命令）
-- ============================================================
-- 为什么没有 INSERT：
--   演示数据依赖 seed 生成的 UUID（租户/公司/角色/用户），把固定 UUID 写死在
--   SQL 里很脆弱——换库名、调整迁移顺序或重新建库后就对不上，且无法随代码演进。
--   seed 是 TypeScript 写的业务逻辑（建角色、建物料、建规格、逐匹入库生成件卡…），
--   由代码保证与当前 schema 匹配，因此**演示数据一律用命令生成**。
--
-- 生成演示数据：
--   pnpm --filter @weftcount/server seed
--
-- 生成内容：
--   · 演示租户「示范织造集团」+ 公司「示范织造厂」
--   · 9 个内置角色（租户管理员/厂长/工艺员/采购员/仓管员/业务员/挡车工/会计/只读访客）
--   · 5 个演示账号（owner/factory/craft/warehouse/loom，密码统一 weft2026）
--   · 演示主数据：棉纱40S / 全棉坯布（含安全库存与采购提前期）、坯布仓 / 成品仓、
--     1-3 号织机、供应商 / 客户
--   · 坯布规格「全棉府绸 120×72」（经纬密 120×72 根/英寸，40S，幅宽 150cm，
--     克重 111.6 g/m² —— 由 shared 工艺内核算出，非手填）
--   · 3 张件卡（PC-<批次号>-01~03，各 100m）供桌面端扫码流程试用
--
-- ⚠️ 安全：seed 会创建**默认密码账号**（weft2026）。
--    正式部署前务必删除演示账号并修改密码—— 见 README「演示账号」一节。
-- ============================================================
